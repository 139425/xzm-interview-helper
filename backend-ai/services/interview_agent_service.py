"""Safe, model-agnostic orchestration for a complete mock interview.

The Java application owns persistence and supplies the interview state on every
call.  This service owns only one bounded decision: choose the next action,
optionally formulate a question, evaluate an answer, or generate a summary.

Raw model reasoning is deliberately never read or returned.  The public
``decision_note`` is generated by the server from the accepted action instead
of forwarding a model's private deliberation.
"""

