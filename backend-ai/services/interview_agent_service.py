_interview_agent_service: Optional[InterviewAgentService] = None


def get_interview_agent_service() -> InterviewAgentService:
    """Return the process-wide service; all mutable interview state remains external."""

    global _interview_agent_service
    if _interview_agent_service is None:
        _interview_agent_service = InterviewAgentService()
    return _interview_agent_service
